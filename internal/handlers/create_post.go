package handlers

import (
	"html/template"
	"log"
	"net/http"
	"strconv"
	"strings"

	"forum/internal/db"
)

type CreatePostData struct {
	Categories   []Category
	Title        string
	Content      string
	ErrorMessage string
}

func CreatePostHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet && r.Method != http.MethodPost {
		w.Header().Set("Allow", "GET, POST")
		ErrorPageHandler(w, r, http.StatusMethodNotAllowed, errMethodNotAllowedTitle, errMethodNotAllowedMessage)
		log.Printf("CreatePostHandler: method %s not allowed\n", r.Method)
		return
	}
	session, err := CheckSession(r)
	if err != nil {
		ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
		return
	}
	if !session.Loggedin {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}

	if r.Method == http.MethodGet {

		categories := LoadCategories()
		tmpl, err := template.ParseFiles("templates/create_post.html")
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler template parse error:", err)
			return
		}

		err = tmpl.Execute(w, CreatePostData{Categories: categories})
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler template execute error:", err)
			return
		}
		return
	}

	if r.Method == http.MethodPost {
		if err := r.ParseForm(); err != nil {
			ErrorPageHandler(w, r, http.StatusBadRequest, "Bad Request", "Invalid form data.")
			return
		}

		title := strings.TrimSpace(r.FormValue("title"))
		content := strings.TrimSpace(r.FormValue("content"))
		categories := r.Form["categories"]
		var categoryIDs []int
		seenCategory := make(map[int]bool)

		if title == "" || content == "" || len(categories) == 0 {
			tmpl, err := template.ParseFiles("templates/create_post.html")
			if err != nil {
				ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
				log.Println("CreatePostHandler template parse error:", err)
				return
			}
			w.WriteHeader(http.StatusBadRequest)
			tmpl.Execute(w, CreatePostData{
				Categories:   LoadCategories(),
				Title:        title,
				Content:      content,
				ErrorMessage: "All fields are required. Please provide a title, content, and select at least one category.",
			})
			return
		}

		for _, catStr := range categories {
			// Check that the category ID is actually a number
			catID, err := strconv.Atoi(catStr)
			if err != nil {
				tmpl, tErr := template.ParseFiles("templates/create_post.html")
				if tErr != nil {
					ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
					log.Println("CreatePostHandler template parse error:", tErr)
					return
				}
				w.WriteHeader(http.StatusBadRequest)
				tmpl.Execute(w, CreatePostData{
					Categories:   LoadCategories(),
					Title:        title,
					Content:      content,
					ErrorMessage: "Please select a valid category.",
				})
				return
			}

			if seenCategory[catID] {
				continue
			}

			// Check that the category ID actually exists in the database
			var exists int
			err = db.DB.QueryRow("SELECT id FROM categories WHERE id = ?", catID).Scan(&exists)
			if err != nil {
				tmpl, tErr := template.ParseFiles("templates/create_post.html")
				if tErr != nil {
					ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
					log.Println("CreatePostHandler template parse error:", tErr)
					return
				}
				w.WriteHeader(http.StatusBadRequest)
				tmpl.Execute(w, CreatePostData{
					Categories:   LoadCategories(),
					Title:        title,
					Content:      content,
					ErrorMessage: "Please select a valid category.",
				})
				return
			}

			seenCategory[catID] = true
			categoryIDs = append(categoryIDs, catID)
		}

		// Use database transaction for atomic post and post_categories insertion
		tx, err := db.DB.Begin()
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler transaction begin error:", err)
			return
		}
		defer tx.Rollback()

		// 1. Insert the post into the posts table
		res, err := tx.Exec("INSERT INTO posts (user_id, title, content) VALUES (?, ?, ?)", session.UserID, title, content)
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler insert post error:", err)
			return
		}

		// 2. Retrieve the newly created post's ID (auto-generated by SQLite)
		postID, err := res.LastInsertId()
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler LastInsertId error:", err)
			return
		}

		// 3. Link each selected category to this post in the junction table (post_categories)
		for _, catID := range categoryIDs {
			_, err := tx.Exec("INSERT INTO post_categories (post_id, category_id) VALUES (?, ?)", postID, catID)
			if err != nil {
				ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
				log.Println("CreatePostHandler insert post_category error:", err)
				return
			}
		}

		if err := tx.Commit(); err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler commit error:", err)
			return
		}

		// 4. Redirect the user to the home page after post is created
		http.Redirect(w, r, "/", http.StatusSeeOther)
		return
	}
}

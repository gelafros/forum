package handlers

import (
	"html/template"
	"log"
	"net/http"
	"strconv"

	"forum/internal/db"
)

func CreatePostHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet && r.Method != http.MethodPost {
		w.Header().Set("Allow", "GET, POST")
		ErrorPageHandler(w, r, http.StatusMethodNotAllowed, errMethodNotAllowedTitle, errMethodNotAllowedMessage)
		log.Printf("CreatePostHandler: method %s not allowed\n", r.Method)
		return
	}
	cookie, err := r.Cookie("session_token")
	if err != nil {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}

	var userID int
	err = db.DB.QueryRow("SELECT user_id FROM sessions WHERE token = ?", cookie.Value).Scan(&userID)
	if err != nil {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}

	if r.Method == "GET" {

		categories := LoadCategories()
		tmpl, err := template.ParseFiles("templates/create_post.html")
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler template parse error:", err)
			return
		}

		err = tmpl.Execute(w, categories)
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler template execute error:", err)
			return
		}
	}

	if r.Method == "POST" {

		title := r.FormValue("title")
		content := r.FormValue("content")
		categories := r.Form["categories"]
		var categoryIDs []int

		if title == "" || content == "" || len(categories) == 0 {
			ErrorPageHandler(w, r, http.StatusBadRequest, "All fields are required", "All fields must be completed")
			return
		}

		for _, catStr := range categories {
			// Check that the category ID is actually a number
			catID, err := strconv.Atoi(catStr)
			if err != nil {
				ErrorPageHandler(w, r, http.StatusBadRequest, "Invalid category", "Please select a valid category")
				return
			}

			// Check that the category ID actually exists in the database
			var exists int
			err = db.DB.QueryRow("SELECT id FROM categories WHERE id = ?", catID).Scan(&exists)
			if err != nil {
				ErrorPageHandler(w, r, http.StatusBadRequest, "Invalid category", "Please select a valid category")
				return
			}

			categoryIDs = append(categoryIDs, catID)
		}

		// 1. Insert the post into the posts table
		res, err := db.DB.Exec("INSERT INTO posts (user_id, title, content) VALUES (?, ?, ?)", userID, title, content)
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler insert post error:", err)
			return
		}

		// 2. Retrieve the newly created post's ID (auto-generated by SQLite)
		postID, err := res.LastInsertId()
		if err != nil {
			ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
			log.Println("CreatePostHandler LastInsertId error:", err)
			return
		}

		// 3. Link each selected category to this post in the junction table (post_categories)
		for _, catID := range categoryIDs {
			_, err := db.DB.Exec("INSERT INTO post_categories (post_id, category_id) VALUES (?, ?)", postID, catID)
			if err != nil {
				ErrorPageHandler(w, r, http.StatusInternalServerError, "Internal Server Error", errInternal)
				log.Println("CreatePostHandler insert post_category error:", err)
				return
			}
		}

		// 4. Redirect the user to the home page after post is created
		http.Redirect(w, r, "/", http.StatusSeeOther)
		return
	}
}
